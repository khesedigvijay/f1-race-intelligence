"""
Export helpers for CSV, JSON data generation and executive markdown/text reports.
"""

import json
from typing import Dict, Any, List
import pandas as pd

def convert_df_to_csv(df: pd.DataFrame) -> bytes:
    """Converts a pandas DataFrame to encoded UTF-8 CSV bytes."""
    return df.to_csv(index=False).encode('utf-8')

def convert_dict_to_json(data: Dict[str, Any]) -> str:
    """Converts dictionary to formatted JSON string."""
    def default_serializer(obj):
        if isinstance(obj, (pd.Timestamp, pd.Timedelta)):
            return str(obj)
        if isinstance(obj, (pd.DataFrame, pd.Series)):
            return obj.to_dict()
        return str(obj)

    return json.dumps(data, indent=2, default=default_serializer)

def generate_race_executive_summary(session_data: Dict[str, Any], insights: List[str]) -> str:
    """
    Constructs an executive markdown summary of the Grand Prix session.
    """
    event = session_data.get("event_name", "Grand Prix")
    circuit = session_data.get("circuit_name", "Circuit")
    season = session_data.get("season", "Current")
    session_type = session_data.get("session_type", "Race")
    date = session_data.get("date", "N/A")
    fastest_lap = session_data.get("fastest_lap", "N/A")
    fastest_driver = session_data.get("fastest_driver", "N/A")
    total_laps = session_data.get("total_laps", 0)
    sc_count = session_data.get("safety_cars", 0)
    vsc_count = session_data.get("vsc", 0)
    is_synth = session_data.get("is_synthetic", False)

    status_tag = "SYNTHETIC DEMO DATASET" if is_synth else "OFFICIAL FASTF1 TIMING TELEMETRY"

    md = f"""# FORMULA 1 RACE INTELLIGENCE EXECUTIVE REPORT
**Event:** {event} ({season})  
**Circuit:** {circuit} | **Session:** {session_type} | **Date:** {date}  
**Data Integrity:** `{status_tag}`  

---

## 1. Key Session Metrics
- **Total Race Distance:** {total_laps} Laps
- **Fastest Lap:** {fastest_lap} ({fastest_driver})
- **Neutralization Events:** {sc_count} Safety Car(s), {vsc_count} Virtual Safety Car(s)

## 2. Key Intelligence Insights
"""
    for ins in insights:
        md += f"- {ins}\n"

    md += """
---
*Generated by Antigravity F1 Race Intelligence Dashboard. Data synchronized and processed using FastF1, SciPy, and Scikit-Learn.*
"""
    return md
